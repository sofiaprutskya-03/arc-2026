// ---------------------------------------------------------------------------
// 1. Піни ESP32 (KS0413 / ESP32 Dev Module)
//    Не використовувати: 6–11 (flash), 12 (strapping, ламає завантаження),
//    34–39 лише вхід і без внутрішньої підтяжки.
